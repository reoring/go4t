#!/usr/bin/env python3
"""Generate native informer families from the pinned inventory and shared descriptor."""
import argparse
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
HEADER = '// Copyright The Kubernetes Authors. SPDX-License-Identifier: Apache-2.0\n// Generated by tools/portgen/GeneratedInformers/generate.py; DO NOT EDIT.\n'
BASE = 'github.com/reoring/gofx/ports/client-go/'
def lower(name): return name[0].lower() + name[1:]
def emit(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + content)
def clientset_getters(upstream):
    result = subprocess.run(
        ['go', 'run', str(pathlib.Path(__file__).with_name('clientset_getters.go')), str(upstream)],
        text=True, capture_output=True, check=True)
    getters = json.loads(result.stdout)
    native = (ROOT/'ports/client-go/kubernetes/clientset.gt').read_text()
    imports = dict(re.findall(r'^import (\w+) "(?:github.com/reoring/gofx/ports/client-go/)?(kubernetes/typed/[^"]+)"$', native, re.M))
    interface = re.search(r'^type Interface = Interface \{([^\n]+)\}', native, re.M)
    if not interface:
        raise ValueError('Missing canonical native clientset Interface')
    fields = re.findall(r'(\w+):\s*func\(\)\s*(\w+)\.(\w+)', interface[1])
    for importpath, getter in getters.items():
        name = lower(getter['method'])
        matches = [(alias, typ) for field, alias, typ in fields if field == name]
        if len(matches) != 1:
            raise ValueError(f'Missing or ambiguous canonical clientset getter: {name}')
        alias, typ = matches[0]
        if imports.get(alias) != importpath.removeprefix('k8s.io/client-go/') or typ != getter['type']:
            raise ValueError(f'Canonical clientset getter type mismatch: {name} for {importpath}')
    return getters
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--upstream', type=pathlib.Path, required=True)
    parser.add_argument('--output-root', type=pathlib.Path, default=ROOT,
                        help='Repository-shaped output root; authoritative inputs always come from the live repository')
    args = parser.parse_args()
    descriptor = json.loads((ROOT/'tools/portgen/resources.json').read_text())
    inventory = json.loads((ROOT/'ports/client-go/upstream-inventory.json').read_text())
    resources = descriptor['resources']
    output = args.output_root/'ports/client-go/informers'
    getters = clientset_getters(args.upstream)
    sources = sorted(source for source in args.upstream.glob('informers/*/*/*.go') if source.name != 'interface.go')
    for source in sources:
        group, version = source.parts[-3:-1]
        importpath = f'k8s.io/client-go/kubernetes/typed/{group}/{version}'
        if importpath not in getters:
            raise ValueError(f'Missing clientset getter for {importpath}')
    groups = {}
    coverage = []
    routes = []
    for source in sources:
        text = source.read_text()
        match = re.search(r'type (\w+)Informer interface', text)
        if not match: raise ValueError(f'No resource informer: {source}')
        kind = match[1]
        group, version = source.parts[-3:-1]
        key = f'k8s.io/api/{group}/{version}.{kind}'
        resource = resources[key]
        if not {'List','Watch'} <= set(resource['verbs']): raise ValueError(f'Informer without list/watch: {key}')
        binding = resource['object_binding']
        listbinding = resource['list_binding']
        if ('namespace string' in text) != (resource['scope'] == 'Namespaced'):
            raise ValueError(f'Scope mismatch between descriptor and informer: {key}')
        field = lower(resource['getter'])
        groupfield = lower(getters[f'k8s.io/client-go/kubernetes/typed/{group}/{version}']['method'])
        client = f'client.{groupfield}().{field}(' + ('namespace' if resource['scope']=='Namespaced' else '') + ')'
        nsarg = 'namespace String, ' if resource['scope']=='Namespaced' else ''
        nscall = 'namespace, ' if nsarg else ''
        imports = f'''package {version}
import "std/map"
import "std/list"
import "{BASE}support/sync"
import "{BASE}support/outcome"
import "{BASE}tools/cache"
import typedclient "{BASE}kubernetes/typed/{group}/{version}"
import "{BASE}informers/internalinterfaces"
import "{BASE}kubernetes"
import "{BASE}features"
import api "{binding['module']}"
import listers "{BASE}listers/{group}/{version}"
import objects "{BASE}deps/objects"
import runtime "{BASE}deps/k8s.io/apimachinery/pkg/runtime"
import meta "{BASE}deps/k8s.io/apimachinery/pkg/apis/meta/v1"
import schema "{BASE}deps/k8s.io/apimachinery/pkg/runtime/schema"
'''
        body = f'''
alias {kind}IndexInformer = cache.TypedInformerView[api.{kind}]
alias {kind}HandlerFuncs = cache.ResourceEventHandler[api.{kind}]
alias {kind}DetailedHandlerFuncs = cache.ResourceEventHandler[api.{kind}]
alias {kind}FilteringHandler = cache.ResourceEventHandler[api.{kind}]
alias {kind}Indexers = Map[String,cache.IndexFunc[api.{kind}]]
func {lower(kind)}HandlerFuncs(add Option[func(api.{kind}) IO[Unit]], update Option[func(api.{kind},api.{kind}) IO[Unit]], delete Option[func(cache.Deleted[api.{kind}]) IO[Unit]]) {kind}HandlerFuncs {{ cache.resourceEventHandlerFuncs(add,update,delete) }}
func {lower(kind)}DetailedHandlerFuncs(add Option[func(api.{kind},Bool) IO[Unit]], update Option[func(api.{kind},api.{kind}) IO[Unit]], delete Option[func(cache.Deleted[api.{kind}]) IO[Unit]]) {kind}DetailedHandlerFuncs {{ cache.resourceEventHandlerDetailedFuncs(add,update,delete) }}
func {lower(kind)}FilteringHandler(accept func(Option[api.{kind}]) IO[Bool], handler cache.ResourceEventHandler[api.{kind}]) {kind}FilteringHandler {{ cache.filteringResourceEventHandler(accept,handler) }}
alias Deleted{kind} = cache.Deleted[api.{kind}]
type {kind}Informer = {kind}Informer {{ informer: func() IO[cache.SharedInformer[runtime.Object]], lister: func() IO[listers.{kind}Lister] }}
type Typed{kind}Informer = Typed{kind}Informer {{ informer: func() IO[cache.SharedInformer[runtime.Object]], typedInformer: func() IO[{kind}IndexInformer], lister: func() IO[listers.{kind}Lister] }}
func to{kind}IndexInformer(informer cache.SharedInformer[runtime.Object]) {kind}IndexInformer {{ cache.typedSharedInformer(informer,api.{binding['descriptor']}()) }}
func toTyped{kind}Informer(informer {kind}Informer) Typed{kind}Informer {{ Typed{kind}Informer(informer.informer,func() => do {{ raw <- informer.informer(); ioPure(to{kind}IndexInformer(raw)) }},informer.lister) }}
func new{kind}InformerWithOptions(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}options internalinterfaces.InformerOptions) IO[cache.SharedInformer[runtime.Object]] {{ do {{
 let resource = {client}
 let access = cache.rawObjectAccess()
 let lw = cache.ListWatcher(func(opts) => do {{
  adjusted <- internalinterfaces.tweakOptions(options.tweakListOptions,opts)
  result <- resource.list(adjusted)
  let raw = api.{listbinding['to_object']}(result.value)
  metadata <- objects.objectListInfo(raw)
  let items = map(typedclient.{lower(kind)}ListAdapter().getItems(result.value),api.{binding['to_object']})
  ioPure(outcome.Outcome(cache.ListResult(items,fst(fst(metadata)),snd(snd(fst(metadata)))),match result.error {{ Some(error) => Some(error); None => snd(metadata) }}))
 }},func(opts) => do {{ adjusted <- internalinterfaces.tweakOptions(options.tweakListOptions,opts); resource.watch(adjusted) }},client.isWatchListSemanticsUnSupported,false)
 clock <- sync.realClock()
 match options.informerName {{ None => ioPure(unit()); Some(name) => do {{ _ <- cache.withResource(name,schema.groupVersionResourceWithResource(schema.groupVersionResourceWithVersion(schema.groupVersionResourceWithGroup(schema.newGroupVersionResource(),"{resource['group']}"),"{version}"),"{resource['resource']}")); ioPure(unit()) }} }}
 informer <- cache.newSharedIndexInformerWithFeatures(featureRegistry,lw,access,func(obj) => outcome.success(obj),options.resyncPeriod,options.indexers,clock)
 ioPure(informer)
}} }}
func newTyped{kind}InformerWithOptions(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}options internalinterfaces.InformerOptions) IO[{kind}IndexInformer] {{ do {{ raw <- new{kind}InformerWithOptions(featureRegistry,client,{nscall}options); ioPure(to{kind}IndexInformer(raw)) }} }}
func new{kind}Informer(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}period Int, indexers Map[String,cache.IndexFunc[runtime.Object]]) IO[cache.SharedInformer[runtime.Object]] {{ new{kind}InformerWithOptions(featureRegistry,client,{nscall}internalinterfaces.InformerOptions(period,indexers,None,None)) }}
func newFiltered{kind}Informer(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}period Int, indexers Map[String,cache.IndexFunc[runtime.Object]], tweak internalinterfaces.TweakListOptionsFunc) IO[cache.SharedInformer[runtime.Object]] {{ new{kind}InformerWithOptions(featureRegistry,client,{nscall}internalinterfaces.InformerOptions(period,indexers,None,Some(tweak))) }}
func newTyped{kind}Informer(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}period Int, indexers {kind}Indexers) IO[{kind}IndexInformer] {{ newTyped{kind}InformerWithOptions(featureRegistry,client,{nscall}internalinterfaces.InformerOptions(period,internalinterfaces.rawIndexers(indexers,api.{binding['descriptor']}()),None,None)) }}
func newTypedFiltered{kind}Informer(featureRegistry features.FeatureRegistry, client kubernetes.Interface, {nsarg}period Int, indexers {kind}Indexers, tweak internalinterfaces.TweakListOptionsFunc) IO[{kind}IndexInformer] {{ newTyped{kind}InformerWithOptions(featureRegistry,client,{nscall}internalinterfaces.InformerOptions(period,internalinterfaces.rawIndexers(indexers,api.{binding['descriptor']}()),None,Some(tweak))) }}
func {field}(factory internalinterfaces.SharedInformerFactory, namespace String, tweak Option[internalinterfaces.TweakListOptionsFunc]) Typed{kind}Informer {{
 let get = func() => internalinterfaces.informerFor(factory,"{key}",func(client,period) => new{kind}InformerWithOptions(factory.featureRegistry,client,{nscall}internalinterfaces.InformerOptions(period,map.mapFromList([("namespace",cache.namespaceIndex(cache.rawObjectAccess()))]),internalinterfaces.informerName(factory),tweak)))
 Typed{kind}Informer(get,func() => do {{ raw <- get(); ioPure(to{kind}IndexInformer(raw)) }},func() => do {{ raw <- get(); ioPure(listers.new{kind}Lister(cache.getIndexer(raw))) }})
}}
'''
        emit(output/group/version/(source.stem+'.gt'),imports+body)
        groups.setdefault(group,{}).setdefault(version,[]).append((field,kind))
        routes.append((resource,group,version,field))
    for group,versions in sorted(groups.items()):
        for version,entries in sorted(versions.items()):
            fields = ', '.join(f'{field}:func() Typed{kind}Informer' for field,kind in entries)
            values = ','.join(f'func() => {field}(factory,namespace,tweak)' for field,kind in entries)
            emit(output/group/version/'interface.gt',f'package {version}\nimport "{BASE}informers/internalinterfaces"\ntype Interface = Interface {{ {fields} }}\nfunc new(factory internalinterfaces.SharedInformerFactory, namespace String, tweak Option[internalinterfaces.TweakListOptionsFunc]) Interface {{ Interface({values}) }}\n')
        imports = ''.join(f'import {v} "{BASE}informers/{group}/{v}"\n' for v in sorted(versions))
        fields = ', '.join(f'{v}:func() {v}.Interface' for v in sorted(versions))
        values = ','.join(f'func() => {v}.new(factory,namespace,tweak)' for v in sorted(versions))
        emit(output/group/'interface.gt',f'package {group}\nimport "{BASE}informers/internalinterfaces"\n'+imports+f'type Interface = Interface {{ {fields} }}\nfunc new(factory internalinterfaces.SharedInformerFactory, namespace String, tweak Option[internalinterfaces.TweakListOptionsFunc]) Interface {{ Interface({values}) }}\n')
    imports = ''.join(f'import {g} "{BASE}informers/{g}"\n' for g in sorted(groups))
    root = f'''package informers
import "{BASE}informers/internalinterfaces"
import "{BASE}support/sync"
import "{BASE}tools/cache"
import "{BASE}support/outcome"
import "{BASE}kubernetes"
import "{BASE}features"
import errors "{BASE}deps/support"
import runtime "{BASE}deps/k8s.io/apimachinery/pkg/runtime"
import schema "{BASE}deps/k8s.io/apimachinery/pkg/runtime/schema"
'''+imports+'''alias SharedInformerFactory = internalinterfaces.SharedInformerFactory
alias SharedInformerOption = internalinterfaces.SharedInformerOption
alias TweakListOptionsFunc = internalinterfaces.TweakListOptionsFunc
alias NewInformerFunc = internalinterfaces.NewInformerFunc
'''
    leaf = (ROOT/'ports/client-go/informers/internalinterfaces/factory.gt').read_text()
    for name in ['withNamespace','withCustomResyncConfig','withTweakListOptions','withTransform','withInformerName','informerName','newSharedInformerFactory','newFilteredSharedInformerFactory','newSharedInformerFactoryWithOptions','informerFor','start','startWithContext','shutdown','waitForCacheSync','waitForCacheSyncWithContext']:
        # Explicit forwarding functions are generated from the authoritative leaf signatures.
        signature = re.search(r'^func '+name+r'(\([^\n]+?) \{',leaf,re.M).group(1)
        parameters = signature[1:signature.index(')')]
        names = re.findall(r'(?:^|, )(\w+) ', parameters)
        root += f'func {name}{signature} {{ internalinterfaces.{name}({",".join(names)}) }}\n'
    for group in sorted(groups): root += f'func {group}(factory SharedInformerFactory) {group}.Interface {{ {group}.new(factory,factory.options.namespace,factory.options.tweakListOptions) }}\n'
    root += '''type GenericInformer = GenericInformer { informer: cache.SharedInformer[runtime.Object], lister: cache.GenericLister[runtime.Object] }
func forResource(factory SharedInformerFactory, gvr schema.GroupVersionResource) IO[outcome.Outcome[Option[GenericInformer]]] {
 let group = schema.groupVersionResourceGetGroup(gvr)
 let version = schema.groupVersionResourceGetVersion(gvr)
 let name = schema.groupVersionResourceGetResource(gvr)
'''
    for resource,group,version,field in routes:
        root += f''' if group == "{resource['group']}" && version == "{version}" && name == "{resource['resource']}" {{ do {{ typed <- {group}(factory).{version}().{field}().informer(); ioPure(outcome.success(Some(GenericInformer(typed,cache.newResourceLister(cache.getIndexer(typed),cache.rawObjectAccess(),schema.groupResourceWithResource(schema.groupResourceWithGroup(schema.newGroupResource(),group),name)))))) }} }} else'''
    root += ' { ioPure(outcome.failure(None,errors.errorNew("no informer found for " + group + "/" + version + ", Resource=" + name))) }\n}\n'
    emit(output/'factory.gt',root)
    upstream_routes = set()
    route_group = route_version = None
    for line in (args.upstream/'informers/generic.go').read_text().splitlines():
        match = re.search(r'// Group=(.*), Version=(.*)', line)
        if match: route_group, route_version = match.groups()
        match = re.search(r'case \w+\.SchemeGroupVersion.WithResource\("([^"]+)"\)', line)
        if match: upstream_routes.add(('' if route_group == 'core' else route_group,route_version,match[1]))
    generated_routes = {(r['group'],v,r['resource']) for r,g,v,f in routes}
    if upstream_routes != generated_routes:
        raise ValueError(f'GVR inventory mismatch: missing={upstream_routes-generated_routes}, extra={generated_routes-upstream_routes}')
    for entry in inventory['files']:
        if not entry['path'].startswith('informers/'): continue
        for decl in entry.get('declarations',[]):
            if decl.get('exported'):
                name = decl['name']
                native = name if decl['kind'] == 'type' else lower(name)
                if name == 'New': native = 'new'
                target = entry['path'].rsplit('/',1)[0]
                if target == 'informers/internalinterfaces': file = target+'/factory.gt'
                elif target == 'informers': file = 'informers/factory.gt'
                elif entry['path'].endswith('/interface.go'): file = target+'/interface.gt'
                else: file = entry['path'][:-3]+'.gt'
                coverage.append({'source':entry['path'],'symbol':name,'line':decl['line'],'receiver':decl.get('receiver'),'native_file':file,'native_symbol':native,'representation':'type or alias' if decl['kind']=='type' else 'callback field' if name in ('Informer','TypedInformer','Lister') else 'function'})
    (output/'coverage.json').write_text(json.dumps({'version':descriptor['source']['version'],'revision':descriptor['source']['revision'],'resources':[r[0]['object_type'] for r in routes],'symbols':coverage},indent=2)+'\n')
    print(f'Generated {len(routes)} resource informers, {len(groups)} groups, {len(coverage)} exported source mappings')
if __name__ == '__main__': main()
