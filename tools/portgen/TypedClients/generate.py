  if r['apply_type']:
   ap,at=r['apply_type'].rsplit('.',1);ca=m.imp(ap.removeprefix('k8s.io/client-go/'));C=m.typ(r['apply_type']);ck=low(at.removesuffix('ApplyConfiguration'))
