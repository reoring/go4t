#!/usr/bin/env python3
"""Generate native listers from pinned sources and the shared resource descriptor."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MODULE = 'github.com/reoring/gofx/ports/client-go/'
HEADER = '// Copyright The Kubernetes Authors. SPDX-License-Identifier: Apache-2.0\n// https://www.apache.org/licenses/LICENSE-2.0\n// Generated by tools/portgen/Listers/generate.py; DO NOT EDIT.\n'

def lower(s):
    return s[0].lower() + s[1:]

def generate(upstream, output_root):
    descriptor = json.loads((ROOT / 'tools/portgen/resources.json').read_text())
    assert descriptor['source']['revision'] == '72c52dd0cc3b9099b36af11290b0304045dd1ada'
    resources = descriptor['resources']
    output = output_root / 'ports/client-go/listers'
    coverage = []
    for source in sorted((upstream / 'listers').rglob('*.go')):
        text = source.read_text()
        rel = source.relative_to(upstream / 'listers')
        if 'expansion' in source.name or source.name in ('doc.go', 'generic_helpers.go'):
            continue
        match = re.search(r'func New(\w+)Lister\(indexer cache.Indexer\)', text)
        if not match:
            raise ValueError(f'Unrecognized lister source: {source}')
        kind = match[1]
        package = re.search(r'"(k8s.io/api/[^\"]+)"', text)[1]
        key = package + '.' + kind
        resource = resources[key]
        singular = re.search(r'\.Resource\("([^\"]+)"\)', text)[1]
        namespaced = kind + 'NamespaceLister' in text
        getter = re.search(r'func \(s \*\w+\) (\w+)\(namespace string\)', text)
        plural = lower(getter[1]) if getter else None
        expansions = source.with_name(source.stem + '_expansion.go')
        methods = []
        if expansions.exists():
            body = expansions.read_text()
            for m in re.finditer(r'func \([^\n]+\) (Get\w+)\((pod|history) \*([\w.]+)\)', body):
                method, arg, arg_type = m.groups()
                history_version = 'v1beta1' if rel.parts[0] == 'extensions' else rel.parts[1]
                native_arg = 'core.Pod' if arg == 'pod' else 'revisionApi.ControllerRevision'
                methods.append((method, arg, native_arg, history_version))
        t = 'api.' + kind
        returns = f'IO[outcome.Outcome[List[{t}]]]'
        fields = [f'list: func(cache.ListSelector) {returns}']
        if namespaced:
            fields.append(f'{plural}: func(String) {kind}NamespaceLister')
        else:
            fields.append(f'get: func(String) IO[outcome.Outcome[Option[{t}]]]')
        fields.extend(f'{lower(method)}: func({arg_type}) {returns}' for method, arg, arg_type, hv in methods)
        lines = [HEADER, '// Source: client-go v0.37.2 listers/' + str(rel), 'package ' + rel.parts[-2],
                 f'import api "{MODULE}deps/{package}"',
                 f'import cache "{MODULE}tools/cache"', f'import listers "{MODULE}listers"',
                 f'import runtime "{MODULE}deps/k8s.io/apimachinery/pkg/runtime"',
                 f'import schema "{MODULE}deps/k8s.io/apimachinery/pkg/runtime/schema"',
                 f'import outcome "{MODULE}support/outcome"']
        if methods:
            lines += [f'import core "{MODULE}deps/k8s.io/api/core/v1"', f'import objects "{MODULE}deps/objects"']
            if any(a == 'history' for _, a, _, _ in methods):
                lines += [f'import revisionApi "{MODULE}deps/k8s.io/api/apps/{methods[-1][3]}"']
        lines += ['', '// Results retain cache object identity and must be treated as read-only.',
                  f'type {kind}Lister = {kind}Lister {{ ' + ', '.join(fields) + ' }']
        if namespaced:
            lines += [f'type {kind}NamespaceLister = {kind}NamespaceLister {{ list: func(cache.ListSelector) {returns}, get: func(String) IO[outcome.Outcome[Option[{t}]]] }}']
        exp_fields = [f'{lower(m)}: func({at}) {returns}' for m, a, at, hv in methods]
        lines += [f'type {kind}ListerExpansion = ' + (f'{kind}ListerExpansion {{ ' + ', '.join(exp_fields) + ' }' if exp_fields else f'{kind}ListerExpansion')]
        if namespaced:
            lines += [f'type {kind}NamespaceListerExpansion = {kind}NamespaceListerExpansion']
        gr = f'schema.groupResourceWithResource(schema.groupResourceWithGroup(schema.newGroupResource(),{json.dumps(resource["group"])}),{json.dumps(singular)})'
        lines += [f'func new{kind}Lister(indexer cache.Indexer[runtime.Object]) {kind}Lister {{ make{kind}Lister(listers.fromRaw(indexer,api.{resource["object_binding"]["descriptor"]}(),{gr})) }}',
                  f'func new{kind}ListerTyped(indexer cache.Indexer[{t}], access cache.ObjectAccess[{t}]) {kind}Lister {{ make{kind}Lister(listers.new(indexer,access,{gr})) }}']
        args = ['indexer.list']
        args += [f'func(namespace) => make{kind}NamespaceLister(indexer.scoped(namespace))'] if namespaced else ['indexer.get']
        for method, arg, arg_type, hv in methods:
            args += [f'func({arg}) => {lower(kind)}{method}(indexer,{arg})']
        lines += [f'func make{kind}Lister(indexer listers.ResourceIndexer[{t}]) {kind}Lister {{ {kind}Lister(' + ','.join(args) + ') }']
        if namespaced:
            lines += [f'func make{kind}NamespaceLister(indexer listers.ResourceIndexer[{t}]) {kind}NamespaceLister {{ {kind}NamespaceLister(indexer.list,indexer.get) }}']
        for method, arg, arg_type, hv in methods:
            lines += expansion(kind, rel, expansions.read_text(), method, arg, arg_type, returns)
            lines += [f'func {lower(method)}(lister {kind}Lister, {arg} {arg_type}) {returns} {{ lister.{lower(method)}({arg}) }}']
        target = output / rel.with_suffix('.gt')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text('\n'.join(lines) + '\n')
        generate_fixture(target, kind, resource, namespaced, plural, methods, expansions)
        coverage.append({'source': 'listers/' + str(rel), 'sha256': hashlib.sha256(text.encode()).hexdigest(), 'output': str(target.relative_to(output_root)), 'object_type': key, 'resource': singular, 'scope': resource['scope'], 'expansions': [m[0] for m in methods]})
    all_sources = []
    for p in sorted((upstream / 'listers').rglob('*.go')):
        declarations = re.findall(r'^(type|func)\s+(?:\([^)]*\)\s+)?([A-Z]\w*)', p.read_text(), re.M)
        exported = [symbol for declaration, symbol in declarations]
        native = {symbol: symbol if declaration == 'type' else lower(symbol) for declaration, symbol in declarations}
        if p.name.endswith('_test.go'):
            native = {symbol: 'generated behavioral fixtures plus generic_helpers_test.gt and selectors_test.gt' for symbol in exported}
        all_sources.append({'source': str(p.relative_to(upstream)), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest(), 'exports': exported, 'native_exports': native, 'role': 'test' if p.name.endswith('_test.go') else ('expansion' if 'expansion' in p.name else 'lister')})
    (output / 'coverage.json').write_text(json.dumps({'source': descriptor['source'], 'resources': coverage, 'sources': all_sources}, indent=2) + '\n')
    print(f'Generated {len(coverage)} typed listers; recorded {len(all_sources)} upstream source files')

def expansion(kind, rel, source, method, arg, arg_type, returns):
    # Error spelling is taken verbatim from each handwritten upstream method.
    body = source[source.index('func ', source.index('// '+method+' returns')):]
    next_method = body.find('\nfunc ', 1)
    if next_method >= 0:
        body = body[:next_method]
    errors = re.findall(r'fmt.Errorf\("([^\"]+)"', body)
    no_labels = 'because it has no labels' in errors[0]
    empty_matches = kind == 'Job' or (kind == 'PodDisruptionBudget' and rel.parts[1] == 'v1')
    check_namespace = '.Namespace != ' in body
    first = errors[0] if no_labels else ''
    last = errors[-1]
    descriptor = 'core.podObjectType()' if arg == 'pod' else 'revisionApi.controllerRevisionObjectType()'
    selector = f'api.{lower(kind)}SpecGetSelector(api.{lower(kind)}GetSpec(candidate))'
    if kind == 'ReplicationController':
        select = f'listers.selectorFromMap({selector})'
    else:
        select = f'listers.selectorFromLabelSelector({selector})'
    # Job expansion values must be shallow snapshots, not retained cache pointers.
    convert = 'objects.shallowCopy(api.jobObjectType(),candidate)' if kind == 'Job' else 'ioPure(candidate)'
    return [f'func {lower(kind)}{method}(indexer listers.ResourceIndexer[api.{kind}], {arg} {arg_type}) {returns} {{',
            f' listers.matchOwners(indexer,objects.toObject({descriptor},{arg}),{str(no_labels).lower()},{json.dumps(first)},{json.dumps(last)},{str(check_namespace).lower()},{str(not empty_matches).lower()},func(candidate) => {select},func(candidate) => cache.rawObjectAccess().namespace(objects.toObject(api.{lower(kind)}ObjectType(),candidate)),func(candidate) => {convert})',
            '}']

def generate_fixture(target, kind, resource, namespaced, plural, methods, expansions):
    lines = [HEADER, 'package ' + target.parent.name,
             f'import api "{resource["object_binding"]["module"]}"',
             f'import cache "{MODULE}tools/cache"',
             f'import objects "{MODULE}deps/objects"',
             f'import meta "{MODULE}deps/k8s.io/apimachinery/pkg/apis/meta/v1"',
             f'import support "{MODULE}deps/support"',
             'import "std/map"']
    if methods:
        lines += [f'import core "{MODULE}deps/k8s.io/api/core/v1"']
        if any(arg == 'history' for _, arg, _, _ in methods):
            lines += [f'import revisionApi "{MODULE}deps/k8s.io/api/apps/{methods[-1][3]}"']
        lines += [f'import fixtures "{MODULE}listers/fixtures"']
    low = lower(kind)
    value = f'api.{low}WithObjectMeta(api.new{kind}(),meta.objectMetaWithName(meta.newObjectMeta(),"example"))'
    getter = f'lister.{plural}("")' if namespaced else 'lister'
    lines += [f'func test{kind}TypedRawLookup() IO[Bool] {{ do {{',
              f' let value = {value}',
              f' let raw = objects.toObject(api.{low}ObjectType(),value)',
              ' let access = cache.rawObjectAccess()',
              ' indexer <- cache.newIndexer(access,map.mapInsert(map.emptyMap(),"namespace",cache.namespaceIndex(access)))',
              ' _ <- indexer.store.add(raw)',
              f' let lister = new{kind}Lister(indexer)',
              ' listed <- lister.list(cache.everythingSelector())',
              f' found <- {getter}.get("example")',
              f' missing <- {getter}.get("absent")',
              f' ioPure(length(listed.value) == 1 && (match found.value {{ None => false; Some(item) => meta.objectMetaGetName(api.{low}GetObjectMeta(item)) == "example" }}) && (match missing.error {{ None => false; Some(error) => support.errorIsNotFound(error) }}))',
              '} }']
    for method, arg, arg_type, version in methods:
        empty_match = kind == 'Job' or (kind == 'PodDisruptionBudget' and target.parent.name == 'v1')
        def obj(name, selection):
            selector = f'fixtures.selector({selection})' if kind != 'ReplicationController' else 'fixtures.labelMap()'
            return f'api.{low}WithObjectMeta(api.{low}WithSpec(api.new{kind}(),api.{low}SpecWithSelector(api.new{kind}Spec(),{selector})),fixtures.metadata("{name}","ns"))'
        arg_value = 'core.podWithObjectMeta(core.newPod(),fixtures.metadata("subject","ns"))' if arg == 'pod' else 'revisionApi.controllerRevisionWithObjectMeta(revisionApi.newControllerRevision(),fixtures.metadata("subject","ns"))'
        lines += [f'func test{kind}{method}Ambiguity() IO[Bool] {{ do {{',
                  ' let access = cache.rawObjectAccess()',
                  ' indexer <- cache.newIndexer(access,map.mapInsert(map.emptyMap(),"namespace",cache.namespaceIndex(access)))',
                  f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("one","1")}))',
                  f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("two","1")}))',
                  f' let subject = {arg_value}',
                  f' result <- new{kind}Lister(indexer).{lower(method)}(subject)',
                  ' ioPure(length(result.value) == 2 && (match result.error { None => true; Some(_) => false }))',
                  '} }']
        if kind != 'ReplicationController':
            lines += [f'func test{kind}{method}NilEmptySelectors() IO[Bool] {{ do {{',
                      ' let access = cache.rawObjectAccess()',
                      ' indexer <- cache.newIndexer(access,map.mapInsert(map.emptyMap(),"namespace",cache.namespaceIndex(access)))',
                      f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("nil","0")}))',
                      f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("empty","2")}))',
                      f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("invalid","3")}))',
                      f' let subject = {arg_value}',
                      f' result <- new{kind}Lister(indexer).{lower(method)}(subject)',
                      f' ioPure(length(result.value) == {1 if empty_match else 0})',
                      '} }']
        # Empty subject labels reject owners except stable PDB's empty selector.
        subject_empty = arg_value.replace('fixtures.metadata("subject","ns")', 'meta.objectMetaWithNamespace(meta.objectMetaWithName(meta.newObjectMeta(),"subject"),"ns")')
        selector_empty = '2' if kind != 'ReplicationController' else '1'
        lines += [f'func test{kind}{method}UnlabelledSubject() IO[Bool] {{ do {{',
                  ' let access = cache.rawObjectAccess()',
                  ' indexer <- cache.newIndexer(access,map.mapInsert(map.emptyMap(),"namespace",cache.namespaceIndex(access)))',
                  f' _ <- indexer.store.add(objects.toObject(api.{low}ObjectType(),{obj("empty",selector_empty)}))',
                  f' result <- new{kind}Lister(indexer).{lower(method)}({subject_empty})',
                  f' ioPure(length(result.value) == {1 if kind == "PodDisruptionBudget" and target.parent.name == "v1" else 0})',
                  '} }']
    target.with_name(target.stem + '_test.gt').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--upstream', type=Path, default=Path('/workspace/wip/go4t/.tmp/client-go-v0.37.2'))
    parser.add_argument('--output-root', type=Path, default=ROOT, help='Destination repository root; use an isolated directory for reproduction proof')
    args = parser.parse_args()
    generate(args.upstream, args.output_root.resolve())
