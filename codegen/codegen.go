// Package codegen lowers a checked go4t program to one Go file per module.
// Checked scalar values use native Go types; erased boundaries and type classes
// use any values and Go dictionaries.
// Constrained instances store their context dictionaries on the method receiver;
// functions, method-local constraints, and generalised lets use explicit params.
// Tuple arities used in annotations, declarations, literals, or patterns receive
// one erased struct each. Partially applied instance heads remain erased: only
// their context constraints contribute dictionary fields.
// Records reuse positional constructor fields, including reordered partial
// patterns; tuple access uses the annotated base arity. Updates copy a single
// evaluated base, and interpolation sends each expression through its Show dictionary.
// Final match arms without source guards omit their proven head guard; refutable
// nested patterns and guarded final arms retain a defensive match panic. Lambda
// parameters, lets and do binds use the same irrefutable pattern bindings; pattern
// lets evaluate their initializer once and remain monomorphic. Boolean operators
// short circuit in Go; non-scalar comparisons dispatch through Eq/Ord dictionaries.
// Small constrained functions get bounded copies for concrete dictionary tuples.
// Derived instances use the ordinary checked instance representation and dictionary ABI.
// Programs declaring the standard List, Option and Result constructors register
// their erased value shapes with rt during init, without exposing generated types to rt.
package codegen

import (
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"go4t/ast"
	goextern "go4t/extern"
	"go4t/types"
)

// generate lowers declarations before module naming and file partitioning.
// An empty goPackage selects main; other names expose Main() rt.IO for embedding instead of
// a Go main function. The input must carry the fully zonked annotations from Check.
// Extern functions adapt checked natural Go signatures or forward the any ABI.
func generate(prog *types.Program, goPackage string) (source []byte, err error) {
	return generateInDir(prog, goPackage, "", Options{})
}

func generateInDir(prog *types.Program, goPackage, dir string, options Options) (source []byte, err error) {
	if prog == nil {
		return nil, fmt.Errorf("nil program")
	}
	if goPackage == "" {
		goPackage = "main"
	}
	if !token.IsIdentifier(goPackage) || goPackage == "_" {
		return nil, fmt.Errorf("invalid Go package name %q", goPackage)
	}
	defer func() {
		if r := recover(); r != nil {
			if e, ok := r.(*types.Error); ok {
				source, err = nil, e
			} else {
				panic(r)
			}
		}
	}()
	g := &generator{
		externs: goextern.Loader{Dir: dir},
		ctors:   make(map[string]*types.Ctor), imports: make(map[string]string),
		instances:  make(map[string]*types.Instance, len(prog.Instances)),
		tuples:     make(map[int]struct{}),
		recordPats: prog.RecordPats,
		funcs:      prog.Funcs,
		locals:     make(map[string]string),
		specials:   make(map[string][]*specialization),
	}
	g.indexSources(prog)
	for _, instance := range prog.Instances {
		g.instances[instanceName(instance)] = instance
	}
	var header, out strings.Builder
	fmt.Fprintf(&header, "// Code generated by go4t. DO NOT EDIT.\npackage %s\nimport (\n\"go4t/rt\"\n", goPackage)
	funcNames := sortedKeys(prog.Funcs)
	for _, name := range funcNames {
		f := prog.Funcs[name]
		if f.Decl.Extern == nil {
			continue
		}
		path := f.Decl.Extern.ImportPath
		if _, found := g.imports[path]; !found {
			alias := fmt.Sprintf("ext_%d", len(g.imports)+1)
			g.imports[path] = alias
			fmt.Fprintf(&header, "%s %s\n", alias, strconv.Quote(path))
		}
	}
	for _, importPath := range options.SideEffectImports {
		fmt.Fprintf(&header, "_ %s\n", strconv.Quote(importPath))
	}
	header.WriteString(")\n")
	g.planSpecializations(prog)
	for _, name := range sortedKeys(prog.DataTypes) {
		d := prog.DataTypes[name]
		fmt.Fprintf(&out, "type %s interface { is%s() }\n", d.Name, d.Name)
		for _, ctor := range d.Ctors {
			g.ctors[ctor.Name] = ctor
			fmt.Fprintf(&out, "type %s struct {", ctorName(ctor))
			if len(ctor.Fields) > 0 {
				out.WriteByte('\n')
			}
			for i, field := range ctor.Fields {
				g.collectType(field)
				fmt.Fprintf(&out, "F%d any\n", i)
			}
			fmt.Fprintf(&out, "}\n%sfunc (*%s) is%s() {}\n", g.typeLine(ctorName(ctor)), ctorName(ctor), d.Name)
		}
	}
	if list, option := prog.DataTypes["List"], prog.DataTypes["Option"]; list != nil && option != nil {
		cons, nilCtor := g.ctors["Cons"], g.ctors["Nil"]
		some, none := g.ctors["Some"], g.ctors["None"]
		if cons != nil && cons.Data == list && len(cons.Fields) == 2 &&
			nilCtor != nil && nilCtor.Data == list && len(nilCtor.Fields) == 0 &&
			some != nil && some.Data == option && len(some.Fields) == 1 &&
			none != nil && none.Data == option && len(none.Fields) == 0 {
			g.tuples[2] = struct{}{}
			g.tuples[3] = struct{}{}
			listLine := g.typeLine("List")
			fmt.Fprintf(&out, `%sfunc rt_tuple2(a, b any) any { return &Tuple2{F0: a, F1: b} }
%sfunc rt_untuple2(p any) (any, any) { t := p.(*Tuple2); return t.F0, t.F1 }
%sfunc rt_tuple3(a, b, c any) any { return &Tuple3{F0: a, F1: b, F2: c} }
%sfunc rt_untuple3(p any) (any, any, any) { t := p.(*Tuple3); return t.F0, t.F1, t.F2 }
`, listLine, listLine, listLine, listLine)
			orderingShape := ""
			if ordering := prog.DataTypes["Ordering"]; ordering != nil {
				lt, eq, gt := g.ctors["LT"], g.ctors["EQ"], g.ctors["GT"]
				if lt != nil && lt.Data == ordering && len(lt.Fields) == 0 &&
					eq != nil && eq.Data == ordering && len(eq.Fields) == 0 &&
					gt != nil && gt.Data == ordering && len(gt.Fields) == 0 {
					fmt.Fprintf(&out, `%sfunc rt_orderingOf(o any) int {
	switch o.(type) {
	case *%s: return -1
	case *%s: return 0
	case *%s: return 1
	default: panic("rt.Shapes.OrderingOf: invalid Ordering")
	}
}
`, g.typeLine("Ordering"), ctorName(lt), ctorName(eq), ctorName(gt))
					orderingShape = "OrderingOf: rt_orderingOf,\n"
				}
			}
			fmt.Fprintf(&out, `%sfunc init() {
	rt.Shapes = rt.ShapeFuncs{
		Cons: %sfunc(h, t any) any { return &%s{F0: h, F1: t} },
		Nil: %sfunc() any { return &%s{} },
		Some: %sfunc(a any) any { return &%s{F0: a} },
		None: %sfunc() any { return &%s{} },
		Uncons: %sfunc(l any) (any, any, bool) {
			if c, ok := l.(*%s); ok { return c.F0, c.F1, true }
			return nil, nil, false
		},
		OptionValue: %sfunc(v any) (any, bool) {
			if s, ok := v.(*%s); ok { return s.F0, true }; return nil, false
		},
		Tuple2: rt_tuple2,
		Untuple2: rt_untuple2,
		Tuple3: rt_tuple3,
		Untuple3: rt_untuple3,
		%s
	}
}
`, g.typeLine("List"),
				g.typeExprLine(ctorName(cons)), ctorName(cons),
				g.typeExprLine(ctorName(nilCtor)), ctorName(nilCtor),
				g.typeExprLine(ctorName(some)), ctorName(some),
				g.typeExprLine(ctorName(none)), ctorName(none),
				g.typeExprLine(ctorName(cons)), ctorName(cons),
				g.typeExprLine(ctorName(some)), ctorName(some), orderingShape)
		}
	}
	if result := prog.DataTypes["Result"]; result != nil {
		ok, err := g.ctors["Ok"], g.ctors["Err"]
		if ok != nil && ok.Data == result && len(ok.Fields) == 1 &&
			err != nil && err.Data == result && len(err.Fields) == 1 {
			resultLine := g.typeLine("Result")
			fmt.Fprintf(&out, `%sfunc rt_ok(a any) any { return &%s{F0: a} }
%sfunc rt_err(e any) any { return &%s{F0: e} }
%sfunc init() {
	rt.Shapes.Ok = rt_ok
	rt.Shapes.Err = rt_err
}
`, resultLine, ctorName(ok), resultLine, ctorName(err), resultLine)
		}
	}
	g.ioErrorShapes(&out, prog)
	g.jsonShapes(&out)
	g.dynShapes(&out, prog)
	g.foreignShapes(&out, prog)
	for _, name := range sortedKeys(prog.Classes) {
		class := prog.Classes[name]
		fmt.Fprintf(&out, "type %s interface {\n", class.Name)
		if class.Super != "" {
			fmt.Fprintln(&out, class.Super)
		}
		for _, method := range class.Methods {
			g.collectType(method.Scheme.Type)
			params := g.dictParams(method.Scheme.Constraints)
			params = append(params, anonymousParams(len(method.Scheme.Type.Params))...)
			fmt.Fprintf(&out, "%s(%s) any\n", exported(method.Name), strings.Join(params, ", "))
		}
		out.WriteString("}\n")
	}
	for _, instance := range prog.Instances {
		g.fileName = g.sources[instance.Decl]
		g.collectType(instance.TypeCon)
		name := instanceName(instance)
		fmt.Fprintf(&out, "type %s struct {", name)
		if instance.Class.Super != "" || len(instance.Context) > 0 {
			out.WriteByte('\n')
		}
		if instance.Class.Super != "" {
			fmt.Fprintf(&out, "%s_%s\n", instance.Class.Super, instance.TypeCon.Name)
		}
		for _, field := range g.dictParams(instance.Context) {
			fmt.Fprintf(&out, "%s\n", field)
		}
		out.WriteString("}\n")
		for _, method := range instance.Decl.Methods {
			var scheme *types.Scheme
			for _, sig := range instance.Class.Methods {
				if sig.Name == method.Name {
					scheme = sig.Scheme
					break
				}
			}
			if scheme == nil {
				g.fail(method.Pos, "unknown method %s.%s", instance.Class.Name, method.Name)
			}
			g.dictScope = g.newDictionaryScope(scheme.Constraints, nil)
			g.dictScope.receiver, g.dictScope.context = "dictself", instance.Context
			params := g.dictScope.declarations()
			restore := g.localScope()
			for _, param := range method.Params {
				params = append(params, mangle(param)+" any")
				g.locals[param] = "any"
			}
			out.WriteString(g.line(method.Pos))
			fmt.Fprintf(&out, "func (dictself %s) %s(%s) any {\n%s}\n", name, exported(method.Name), strings.Join(params, ", "), g.returning("any", func() string { return g.block(method.Body) }))
			restore()
		}
	}
	for _, name := range funcNames {
		out.WriteString(g.emitFunction(prog.Funcs[name], functionName(name)))
	}
	for _, spec := range g.specialOrder {
		g.special, g.typeArgs = spec, spec.types
		out.WriteString(g.emitFunction(spec.function, spec.name))
		g.special, g.typeArgs = nil, nil
	}
	if prog.Main == nil {
		return nil, fmt.Errorf("program has no main function")
	}
	g.fileName = g.sources[prog.Main.Decl]
	out.WriteString(g.line(prog.Main.Decl.Pos))
	if goPackage == "main" {
		fmt.Fprintf(&out, "func main() { rt.RunMain(%s()) }\n", functionName(prog.Main.Name))
	} else {
		fmt.Fprintf(&out, "func Main() rt.IO { return %s().(rt.IO) }\n", functionName(prog.Main.Name))
	}
	if g.contextIO {
		header.WriteString("import \"context\"\n")
	}
	arities := make([]int, 0, len(g.tuples))
	for arity := range g.tuples {
		arities = append(arities, arity)
	}
	sort.Ints(arities)
	for _, arity := range arities {
		fmt.Fprintf(&header, "type Tuple%d struct {\n", arity)
		for i := range arity {
			fmt.Fprintf(&header, "F%d any\n", i)
		}
		header.WriteString("}\n")
	}
	if g.ordering {
		line := g.typeLine("Ordering")
		fmt.Fprintf(&header, `%sfunc ord_lt(o any) bool { _, ok := o.(*Ordering_LT); return ok }
%sfunc ord_le(o any) bool { _, ok := o.(*Ordering_GT); return !ok }
%sfunc ord_gt(o any) bool { _, ok := o.(*Ordering_GT); return ok }
%sfunc ord_ge(o any) bool { _, ok := o.(*Ordering_LT); return !ok }
`, line, line, line, line)
	}
	header.WriteString(out.String())
	unformatted := []byte(header.String())
	source, err = format.Source(unformatted)
	if err != nil {
		return unformatted, fmt.Errorf("format generated Go: %w", err)
	}
	return source, nil
}

type generator struct {
	ctors        map[string]*types.Ctor
	recordPats   map[*ast.PRecord]types.RecordPat
	imports      map[string]string
	externs      goextern.Loader
	instances    map[string]*types.Instance
	tuples       map[int]struct{}
	dictScope    dictionaryScope
	dictIDs      map[*types.TVar]int
	sources      map[ast.Decl]string
	typeSources  map[string]sourceLocation
	aliases      map[string]*ast.AliasDecl
	fileName     string
	next         int
	ordering     bool
	contextIO    bool
	funcs        map[string]*types.FuncInfo
	locals       map[string]string
	patternTypes map[ast.Pattern]types.Type
	returnRep    string
	typeArgs     map[string]types.Type
	special      *specialization
	specials     map[string][]*specialization
	specialOrder []*specialization
}

type dictionaryScope struct {
	receiver string
	params   []types.Constraint // Parameters declared in this lexical scope.
	names    []string           // Go names fixed when the scope is entered.
	context  []types.Constraint // Receiver fields have their own naming scope.
	parent   *dictionaryScope
}

func (scope *dictionaryScope) declarations() []string {
	params := make([]string, len(scope.params))
	for i, constraint := range scope.params {
		params[i] = scope.names[i] + " " + constraint.Class
	}
	return params
}

func (scope *dictionaryScope) hasName(name string) bool {
	for ; scope != nil; scope = scope.parent {
		for _, bound := range scope.names {
			if bound == name {
				return true
			}
		}
	}
	return false
}

func (g *generator) fail(pos ast.Pos, format string, args ...any) {
	panic(types.NewError(pos, format, args...))
}

func (g *generator) ann(expr ast.Expr) *types.Ann {
	a, ok := (*expr.AnnSlot()).(*types.Ann)
	if !ok || a == nil {
		g.fail(expr.GetPos(), "expression has no annotation")
	}
	return a
}

func (g *generator) collectAnnotation(expr ast.Expr) {
	if ann, ok := (*expr.AnnSlot()).(*types.Ann); ok && ann != nil {
		g.collectType(ann.Type)
		for _, typ := range ann.Inst {
			g.collectType(typ)
		}
	}
}

func (g *generator) collectType(typ types.Type) {
	switch typ := types.Unalias(typ).(type) {
	case *types.TCon:
		if arity, ok := types.IsTuple(typ); ok {
			g.tuples[arity] = struct{}{}
		}
	case *types.TApp:
		g.collectType(typ.Fun)
		for _, arg := range typ.Args {
			g.collectType(arg)
		}
	case *types.TFunc:
		for _, param := range typ.Params {
			g.collectType(param)
		}
		g.collectType(typ.Ret)
	}
}

func (g *generator) tupleName(arity int) string {
	g.tuples[arity] = struct{}{}
	return fmt.Sprintf("Tuple%d", arity)
}

func (g *generator) fresh() string {
	name := fmt.Sprintf("_go4t%d", g.next)
	g.next++
	return name
}

func (g *generator) dictParams(constraints []types.Constraint) []string {
	params := make([]string, len(constraints))
	for i, constraint := range constraints {
		params[i] = g.dictField(constraint, constraints) + " " + constraint.Class
	}
	return params
}

func (g *generator) dictID(param *types.TVar) int {
	if g.dictIDs == nil {
		g.dictIDs = make(map[*types.TVar]int)
	}
	if g.dictIDs[param] == 0 {
		g.dictIDs[param] = len(g.dictIDs) + 1
	}
	return g.dictIDs[param]
}

func (g *generator) dictField(constraint types.Constraint, constraints []types.Constraint) string {
	param, ok := constraint.Arg.(*types.TVar)
	if !ok || param == nil {
		g.fail(ast.Pos{}, "dictionary constraint does not name a type parameter")
	}
	count, shadowed := 0, false
	for _, candidate := range constraints {
		if variable, ok := candidate.Arg.(*types.TVar); ok {
			if variable == param {
				count++
			} else if variable.Name == param.Name {
				shadowed = true
			}
		}
	}
	name := "dict_" + param.Name
	if count > 1 {
		name += "_" + constraint.Class
	}
	if shadowed {
		name += fmt.Sprintf("_%d", g.dictID(param))
	}
	return name
}

// A nested dictionary binder must not hide a captured rigid parameter, even
// when their source spellings match. Keep names stable in each lexical scope.
func (g *generator) newDictionaryScope(constraints []types.Constraint, parent *dictionaryScope) dictionaryScope {
	scope := dictionaryScope{params: constraints, names: make([]string, len(constraints)), parent: parent}
	for i, constraint := range constraints {
		name := g.dictField(constraint, constraints)
		if scope.hasName(name) {
			name += fmt.Sprintf("_%d", g.dictID(constraint.Arg.(*types.TVar)))
			for scope.hasName(name) {
				name += "_"
			}
		}
		scope.names[i] = name
	}
	return scope
}

func (g *generator) dict(dict *types.DictRef) string {
	if dict == nil {
		g.fail(ast.Pos{}, "missing dictionary annotation")
	}
	if dict.Kind == types.DictParam && g.special != nil {
		if concrete, ok := g.special.dicts[types.Constraint{Arg: dict.Param, Class: dict.ParamClass}]; ok {
			return g.dict(&concrete)
		}
	}
	switch dict.Kind {
	case types.DictInstance:
		if dict.Instance != nil {
			return g.instanceDict(dict.Instance, dict.Args)
		}
	case types.DictParam:
		for scope := &g.dictScope; scope != nil; scope = scope.parent {
			for i, constraint := range scope.params {
				if constraint.Arg == dict.Param && constraint.Class == dict.ParamClass {
					return scope.names[i]
				}
			}
			if scope.receiver != "" {
				for _, constraint := range scope.context {
					if constraint.Arg == dict.Param && constraint.Class == dict.ParamClass {
						return scope.receiver + "." + g.dictField(constraint, scope.context)
					}
				}
			}
		}
	case types.DictSuper:
		return g.dict(dict.Super)
	}
	g.fail(ast.Pos{}, "invalid dictionary annotation")
	return ""
}

func (g *generator) instanceDict(instance *types.Instance, args []types.DictRef) string {
	if len(args) != len(instance.Context) {
		g.fail(ast.Pos{}, "invalid dictionary annotation")
	}
	name := instanceName(instance)
	if len(args) == 0 {
		return name + "{}"
	}
	var out strings.Builder
	out.WriteString(name)
	out.WriteByte('{')
	if instance.Class.Super != "" {
		superName := instance.Class.Super + "_" + instance.TypeCon.Name
		super := g.instances[superName]
		if super == nil {
			g.fail(ast.Pos{}, "missing superclass instance %s[%s]", instance.Class.Super, instance.TypeCon.Name)
		}
		if len(instance.SuperArgs) != len(super.Context) {
			g.fail(ast.Pos{}, "invalid superclass dictionary annotation")
		}
		superArgs := make([]types.DictRef, len(instance.SuperArgs))
		for i := range instance.SuperArgs {
			ref := &instance.SuperArgs[i]
			// Superclass interfaces are embedded, so upcasts do not change the
			// emitted value. Substitute the leaf parameter with this use's arg.
			for ref != nil && ref.Kind == types.DictSuper {
				ref = ref.Super
			}
			if ref == nil || ref.Kind != types.DictParam {
				g.fail(ast.Pos{}, "invalid superclass dictionary annotation")
			}
			found := false
			for j, constraint := range instance.Context {
				if constraint.Arg == ref.Param && constraint.Class == ref.ParamClass {
					superArgs[i] = args[j]
					found = true
					break
				}
			}
			if !found {
				g.fail(ast.Pos{}, "invalid superclass dictionary annotation")
			}
		}
		out.WriteString(superName)
		out.WriteString(": ")
		out.WriteString(g.instanceDict(super, superArgs))
		out.WriteString(", ")
	}
	for i, constraint := range instance.Context {
		if i > 0 {
			out.WriteString(", ")
		}
		out.WriteString(g.dictField(constraint, instance.Context))
		out.WriteString(": ")
		out.WriteString(g.dict(&args[i]))
	}
	out.WriteByte('}')
	return out.String()
}

func sortedKeys[V any](items map[string]V) []string {
	keys := make([]string, 0, len(items))
	for key := range items {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func mangle(name string) string { return name + "_" }

// The implicitly callable prelude primitive must remain distinct from a local
// ioPure binding even before module renaming. ext_ is a reserved source prefix.
func functionName(name string) string {
	if name == "ioPure" {
		return "ext_ioPure_"
	}
	return mangle(name)
}

func exported(name string) string {
	r, n := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(r)) + name[n:]
}

func ctorName(ctor *types.Ctor) string { return ctor.Data.Name + "_" + ctor.Name }

func instanceName(instance *types.Instance) string {
	return instance.Class.Name + "_" + instance.TypeCon.Name
}

func anonymousParams(arity int) []string {
	params := make([]string, arity)
	for i := range params {
		params[i] = fmt.Sprintf("a%d any", i)
	}
	return params
}

func anonymousArgs(arity int) []string {
	args := make([]string, arity)
	for i := range args {
		args[i] = fmt.Sprintf("a%d", i)
	}
	return args
}
