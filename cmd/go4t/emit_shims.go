type pendingShim struct {
	owner, filename string
	source          []byte
}

// Loading and caching are package-wide. Materialization waits for checked
// reachability, but precedes codegen's Go ABI inspection of these packages.
func (b *goImportBinder) emitShims(p *types.Program) ([]string, error) {
	roots := make(map[string]map[string]bool)
	owners := make(map[string]bool)
	for _, f := range p.Funcs {
		ref := f.Decl.Extern
		if ref == nil {
			continue
		}
		if owner, ok := strings.CutPrefix(p.Owners[f.Name], "go:"); ok {
			owners[owner] = true // also includes natural-ABI calls without a shim
		}
		if shim, ok := b.shims[ref.ImportPath]; ok {
			owners[shim.owner] = true
			if roots[ref.ImportPath] == nil {
				roots[ref.ImportPath] = make(map[string]bool)
			}
			roots[ref.ImportPath][ref.Name] = true
		}
	}
	for _, owner := range sortedPaths(owners) {
		if err := b.bindClassifiers(owner); err != nil {
			return nil, err
		}
	}
	sort.Strings(b.sideEffectImports)
	for _, path := range b.sideEffectImports {
		if roots[path] == nil {
			roots[path] = make(map[string]bool)
		}
		roots[path]["init"] = true
	}
	b.emitted = make(map[string][]byte, len(roots))
	for _, path := range sortedPaths(roots) {
		shim := b.shims[path]
		source := shim.source
		if shim.filename != "shim.go" { // generic companions already contain one concrete call
			var err error
			source, err = selectShim(source, roots[path])
			if err != nil {
				return nil, fmt.Errorf("select shim %s: %w", path, err)
			}
		}
		rel := strings.TrimPrefix(path, b.shimPrefix+"/")
		b.emitted[filepath.Join(filepath.FromSlash(rel), shim.filename)] = source
	}
	return b.sideEffectImports, writeShims(b.outputDir, b.emitted)
}

func sortedPaths[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// A package shim consists of freestanding wrapper/converter functions and
// explicitly aliased imports. Follow local Go declaration identities, not
// text: a selector of the same spelling on the original Go package is not a
// recursive call. Keep source order, including the generated-file marker.
func selectShim(source []byte, roots map[string]bool) ([]byte, error) {
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, "shim.go", source, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	live := make(map[*ast.FuncDecl]bool)
	imports := make(map[string]bool)
	var mark func(*ast.FuncDecl)
	mark = func(f *ast.FuncDecl) {
		if live[f] {
			return
		}
		live[f] = true
		ast.Inspect(f, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.Ident:
				if x.Obj != nil {
					if other, ok := x.Obj.Decl.(*ast.FuncDecl); ok {
						mark(other)
					}
				}
			case *ast.SelectorExpr:
				if id, ok := x.X.(*ast.Ident); ok && id.Obj == nil {
					imports[id.Name] = true
				}
			}
			return true
		})
	}
	for _, d := range file.Decls {
		if f, ok := d.(*ast.FuncDecl); ok && roots[f.Name.Name] {
			mark(f)
		}
	}
	keep := file.Decls[:0]
	for _, d := range file.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			if live[d] {
				keep = append(keep, d)
			}
		case *ast.GenDecl:
			if d.Tok != token.IMPORT {
				return nil, fmt.Errorf("unexpected %s declaration in binding template", d.Tok)
			}
			specs := d.Specs[:0]
			for _, spec := range d.Specs {
				if imports[spec.(*ast.ImportSpec).Name.Name] {
					specs = append(specs, spec)
				}
			}
			d.Specs = specs
			if len(specs) != 0 {
				keep = append(keep, d)
			}
		}
	}
	file.Decls = keep
	var out bytes.Buffer
	err = format.Node(&out, set, file)
	return out.Bytes(), err
}

// Remove only obsolete compiler-owned files, even when re-emitting a program
// with no go: imports over one that previously had shims.
func writeShims(dir string, files map[string][]byte) error {
	root := filepath.Join(dir, "go4tbind")
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if path == root && os.IsNotExist(err) {
			return nil
		}
		if err != nil || !entry.Type().IsRegular() || !strings.HasSuffix(path, ".go") {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil || files[rel] != nil {
			return err
		}
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(source, []byte("// Code generated by go4t bind ")) || bytes.HasPrefix(source, []byte("// Code generated by go4t generic instantiation.")) {
			return os.Remove(path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, rel := range sortedPaths(files) {
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, files[rel], 0o644); err != nil {
			return err
		}
	}
	return nil
}
