#!/usr/bin/env python3
"""Generate native external-dependency bindings from the pinned structured AST graph.
No client-go implementation is read or emitted by this generator.
"""
import argparse
import hashlib
import json
import pathlib
import re

BASE = pathlib.Path(__file__).resolve().parents[2]
HOST = 'github.com/reoring/gofx/ports/client-go/host/deps'
MOD = 'github.com/reoring/gofx/ports/client-go'


def lower(name):
    name=name.split('[',1)[0]
    if name.isupper():
        return name.lower()
    return name[0].lower() + name[1:]


def exported(name):
    return bool(name) and name[0].isupper()


def safe(name):
    return re.sub('[^A-Za-z0-9_]', '_', name)

def manual_adapters():
    manual={}
    for relative in ('deps/support/values.gfx','deps/codec/codec.gfx','deps/objects/objects.gfx'):
        operations=[]
        for line in (BASE/relative).read_text().splitlines():
            if not line.startswith('extern func '):continue
            declaration,host=line.split(' = ',1)
            name=declaration[len('extern func '):].split('(',1)[0].split('[',1)[0]
            operations.append({'name':name,'declaration':declaration,'host':host})
        manual[relative]={'operations':operations,'scope':'Generic external dependency conversion/access/effect only; no client-go policy'}
    return manual



def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--contract', type=pathlib.Path, default=pathlib.Path(__file__).with_name('contract.json'))
    ap.add_argument('--target', type=pathlib.Path, default=pathlib.Path(__file__).with_name('target.json'))
    ap.add_argument('--output-root', type=pathlib.Path, help='Write generated outputs to an isolated module-shaped tree; inputs and ABI baseline remain live and read-only')
    ap.add_argument('--manual-adapters-only', action='store_true', help='Refresh only the manual adapter ledger and coverage metadata, preserving all generated bindings')
    args = ap.parse_args()
    output_root=args.output_root.resolve() if args.output_root else BASE
    if args.output_root and output_root==BASE:
        ap.error('--output-root must differ from the live module root')
    def save(path,text):
        path=output_root/path.relative_to(BASE)
        path.parent.mkdir(parents=True,exist_ok=True)
        temporary=path.with_name('.'+path.name+'.tmp')
        temporary.write_text(text)
        temporary.replace(path)
    if args.manual_adapters_only:
        coverage=json.loads((BASE/'deps/coverage.json').read_text())
        manual=manual_adapters()
        coverage['manual_adapters']=manual
        save(BASE/'tools/binddeps/manual-adapters.json',json.dumps(manual,indent=2,sort_keys=True)+'\n')
        save(BASE/'deps/coverage.json',json.dumps(coverage,indent=2,sort_keys=True)+'\n')
        print('Refreshed manual adapter metadata only')
        return
    graph = json.loads(args.contract.read_text())
    previous_path=BASE/'deps/coverage.json'
    previous=json.loads(previous_path.read_text()) if previous_path.exists() else {}
    corrections=json.loads((BASE/'tools/binddeps/mode-corrections.json').read_text())
    authorized={}
    for id,correction in corrections.items():
        authorized[('types',id)]={'mode':correction['mode']}
        for field in correction['fields']:
            authorized[('fields',id+'.'+field)]={'status':correction['field_status']}
        for method,changes in correction['methods'].items():
            authorized[('calls',id+'.'+method)]={**changes,'mode':correction['mode']}
    source_hash=hashlib.sha256(args.contract.read_bytes()).hexdigest()
    header=['// Code generated by tools/binddeps/generate.py; DO NOT EDIT.',
            '// Source: client-go v0.37.2 and exact external dependency declarations.',
            '// Kubernetes-derived declarations are licensed under Apache-2.0.',
            '// https://www.apache.org/licenses/LICENSE-2.0',
            '// Source graph SHA-256: '+source_hash]
    target=json.loads(args.target.read_text())
    defs={k:[d for d in ds if target['matches'].get(d['source'],True)] for k,ds in graph['definitions'].items()}
    inactive=[k for k,ds in defs.items() if not ds]
    defs={k:ds for k,ds in defs.items() if ds}
    types = {k: v[0] for k, v in defs.items() if v[0]['kind'] == 'type'}
    documentary={id:types.pop(id) for id in ('unsafe.ArbitraryType','unsafe.IntegerType') if id in types}
    coverage = {'schema_version': 1, 'source_authority': graph['authority'], 'types': {}, 'fields': {}, 'calls': {}, 'uncovered': []}
    coverage['target']={k:v for k,v in target.items() if k!='matches'}
    coverage['inactive_on_target']=inactive
    coverage['documentary_not_runtime']={id:{'source':d['source'],'line':d['line'],'reason':'Go unsafe documentation-only pseudo-type; not an actual exported Go type'} for id,d in documentary.items()}
    names = {k: (safe(k.rsplit('.', 1)[1]) if exported(k.rsplit('.', 1)[1]) else 'Internal_' + safe(k.rsplit('.', 1)[1])) + '_' + hashlib.sha256(k.encode()).hexdigest()[:12] for k in types}
    imports = {}
    packages = {}
    hosts = []
    registry = []
    funcs = []
    interface_hosts = []
    anonymous={}

    def local_type(n):
        base=n if exported(n) else 'Internal_'+n
        return base+'Go' if base in ('Map','List','Set','Option','Result','Ordering','IO','Int','Float','Bool','String','Unit','Never') else base

    def structural(n,seen=()):
        if isinstance(n,dict):
            if n.get('kind')=='ref' and n['id'] in types and n['id'] not in seen and types[n['id']]['shape']['kind']=='alias':
                return structural(types[n['id']]['shape']['underlying'],seen+(n['id'],))
            return {k:structural(v,seen) for k,v in n.items() if k not in ('line','doc','comment')}
        if isinstance(n,list): return [structural(x,seen) for x in n]
        return n

    def interface_id(n):
        encoded=json.dumps(structural(n),sort_keys=True,separators=(',',':')).encode()
        return 'anonymous.Interface_'+hashlib.sha256(encoded).hexdigest()[:16]

    def scan_interfaces(node,owner,root_node=None):
        if isinstance(node,dict):
            if node.get('kind')=='interface' and node.get('members') and node is not root_node:
                id=interface_id(node)
                if id not in types:
                    types[id]={'id':id,'kind':'type','source':owner['source'],'line':owner['line'],'shape':{'kind':'named','underlying':node,'type_parameters':[]},'synthetic':True}
                    names[id]=id.split('.')[-1]
            for value in node.values():scan_interfaces(value,owner,root_node)
        elif isinstance(node,list):
            for value in node:scan_interfaces(value,owner,root_node)

    for variants in defs.values():
        for declaration in variants:
            root_node=declaration['shape'].get('underlying') if declaration['kind']=='type' else None
            scan_interfaces(declaration['shape'],declaration,root_node)

    def issue(id, reason):
        coverage['uncovered'].append({'id': id, 'reason': reason})

    def accessible(id):
        p, n = id.rsplit('.', 1)
        if p=='unsafe' and n!='Pointer':return False
        return exported(n) and not p.startswith('internal/') and not p.endswith('/internal') and '/internal/' not in p and p not in ('C','internal')

    def imp(p):
        if p not in imports:
            imports[p] = 'd' + str(len(imports))
        return imports[p]

    def underlying(node, seen=()):
        if isinstance(node, dict) and node.get('kind') == 'ref' and node['id'] in types and node['id'] not in seen:
            return underlying(types[node['id']]['shape']['underlying'], seen + (node['id'],))
        return node

    def params_of(shape):
        out = []
        for f in shape.get('parameters', []):
            out.extend([f['type']] * max(1, len(f['names'])))
        if out and out[0] == {'kind': 'ref', 'id': 'context.Context'}:
            out.pop(0)
        return out

    def results_of(shape):
        out = []
        for f in shape.get('results', []):
            out.extend([f['type']] * max(1, len(f['names'])))
        return out

    def tuple_type(xs):
        if not xs:
            return 'Unit'
        if len(xs) == 1:
            return xs[0]
        return '(' + xs[0] + ', ' + tuple_type(xs[1:]) + ')'

    def mutable_arg(n,seen=()):
        k=n['kind']
        if k in ('slice','map','variadic'):return True
        if k=='pointer':
            e=n['element']
            if e.get('kind')=='ref' and e['id'] in types and mode(e['id'],types[e['id']])=='identity':return False
            return True
        if k=='interface':return not n['members']
        if k=='array':return mutable_arg(n['element'],seen)
        if k=='instantiation':return mutable_arg(n['base'],seen)
        if k=='ref' and n['id'] in types and n['id'] not in seen:
            id=n['id'];d=types[id]
            if id in ('k8s.io/apimachinery/pkg/runtime.Object','k8s.io/apimachinery/pkg/apis/meta/v1.Object','k8s.io/apimachinery/pkg/runtime/schema.ObjectKind'):return True
            if mode(id,d)=='identity':return False
            return mutable_arg(d['shape']['underlying'],seen+(id,))
        if k=='struct':return any(mutable_arg(f['type'],seen) for f in n['fields'])
        return False

    def update_indices(shape):
        return [i for i,p in enumerate(params_of(shape)) if mutable_arg(p)]

    def outcome_type(shape):
        ps=params_of(shape);indices=update_indices(shape)
        results=tuple_type([native(x) for x in results_of(shape)])
        if not indices:return results
        return '('+tuple_type([native(ps[i]) for i in indices])+', '+results+')'

    def update_metadata(shape):
        entries=[]
        for field in shape.get('parameters',[]):
            entries.extend((name,field['type']) for name in (field['names'] or ['']))
        offset=1 if entries and entries[0][1]=={'kind':'ref','id':'context.Context'} else 0
        return [{'native_parameter_index':i,'go_parameter_index':i+offset,'source_name':entries[i+offset][0],'native_name':'p'+str(i)} for i in update_indices(shape)]

    def native(n):
        k = n['kind']
        if k == 'predeclared':
            name = n['name']
            if name == 'error': return 'Option[support.Error]'
            if name == 'any': return 'Option[support.Any]'
            if name in ('uint', 'uint64', 'uintptr'): return 'support.UInt64'
            if name in ('complex64', 'complex128'): return '(Float, Float)'
            if name == 'bool': return 'Bool'
            if name == 'string': return 'String'
            if name in ('float32', 'float64'): return 'Float'
            if name == 'comparable': raise ValueError('constraint is not a runtime value')
            return 'Int'
        if k == 'ref':
            id = n['id']
            if id not in types: raise ValueError('unresolved named type ' + id)
            target = types[id]['shape']
            if target['kind'] == 'alias': return native(target['underlying'])
            base = 'canonical.' + names[id]
            tps = target.get('type_parameters', [])
            if tps: raise ValueError('uninstantiated generic type ' + id)
            if underlying(target['underlying']).get('kind') == 'interface': return 'Option[' + base + ']'
            return base
        if k == 'type_parameter': return n['name']
        if k == 'pointer': return 'Option[' + native(n['element']) + ']'
        if k in ('slice', 'variadic'):
            e = n['element']
            if e.get('kind') == 'predeclared' and e.get('name') in ('byte', 'uint8'):
                return 'Option[String]' if k == 'slice' else 'List[Int]'
            return ('Option[' if k == 'slice' else '') + 'List[' + native(e) + ']' + (']' if k == 'slice' else '')
        if k == 'array': return 'List[' + native(n['element']) + ']'
        if k == 'map':
            key='support.PointerKey['+native(n['key']['element'])+']' if n['key'].get('kind')=='pointer' else native(n['key'])
            return 'support.ForeignMap[' + key + ', ' + native(n['element']) + ']'
        if k == 'channel': return 'support.Channel[' + native(n['element']) + ']'
        if k == 'function': return 'func(' + ', '.join(native(x) for x in params_of(n)) + ') IO[' + outcome_type(n) + ']'
        if k == 'interface':
            if not n['members']:return 'Option[support.Any]'
            return 'Option[canonical.'+names[interface_id(n)]+']'
        if k=='struct':
            if not n['fields']: return 'Unit'
            signature=json.dumps(structural(n),sort_keys=True,separators=(',',':'))
            name='Anonymous_'+hashlib.sha256(signature.encode()).hexdigest()[:16]
            anonymous[name]=n
            return 'canonical.'+name
        if k == 'instantiation':
            b = n['base']
            if b.get('kind') != 'ref' or b['id'] not in names: raise ValueError('unsupported generic base')
            return 'canonical.' + names[b['id']] + '[' + ', '.join(native(x) for x in n['arguments']) + ']'
        raise ValueError('unmapped AST kind ' + k)

    def go(n):
        k = n['kind']
        if k == 'ref':
            p, name = n['id'].rsplit('.', 1)
            if p=='anonymous':return go(types[n['id']]['shape']['underlying'])
            if not accessible(n['id']): raise ValueError('inaccessible Go type ' + n['id'])
            return imp(p) + '.' + name
        if k == 'predeclared': return n['name']
        if k == 'type_parameter': return n['name']
        if k == 'pointer': return '*' + go(n['element'])
        if k in ('slice', 'variadic'): return '[]' + go(n['element'])
        if k == 'array': return '[' + n['length_expression'] + ']' + go(n['element'])
        if k == 'map': return 'map[' + go(n['key']) + ']' + go(n['element'])
        if k == 'channel': return {1: 'chan<- ', 2: '<-chan ', 3: 'chan '}[n['direction']] + go(n['element'])
        if k == 'instantiation': return go(n['base']) + '[' + ','.join(go(x) for x in n['arguments']) + ']'
        if k == 'interface':
            if not n['members']: return 'any'
            entries=[]
            for f in n['members']:
                if f['names']:
                    for name in f['names']:entries.append(name+go(f['type']).removeprefix('func'))
                else:entries.append(go(f['type']))
            return 'interface {'+';'.join(entries)+'}'
        if k == 'function':
            ps=[]
            for f in n['parameters']:
                spelling='...'+go(f['type']['element']) if f['type'].get('kind')=='variadic' else go(f['type'])
                ps.extend([spelling] * max(1,len(f['names'])))
            rs=[go(x) for x in results_of(n)]
            return 'func(' + ','.join(ps) + ') (' + ','.join(rs) + ')'
        if k=='struct':
            parts=[]
            for f in n['fields']:
                if any(not exported(x) for x in f['names']):raise ValueError('anonymous private field identity is package-scoped')
                prefix=(','.join(f['names'])+' ') if f['names'] else ''
                tag=(' '+json.dumps(f['tag'])) if f['tag'] else ''
                parts.append(prefix+go(f['type'])+tag)
            return 'struct {'+';'.join(parts)+'}'
        raise ValueError('unrendered Go type ' + k)

    def mode(id, d):
        u = underlying(d['shape']['underlying'])
        if id in corrections:return corrections[id]['mode']['to']
        if id.startswith('k8s.io/api/') or id.startswith(('k8s.io/apimachinery/pkg/apis/meta/', 'k8s.io/apimachinery/pkg/runtime/schema.', 'k8s.io/apimachinery/pkg/types.', 'k8s.io/apimachinery/pkg/util/intstr.', 'k8s.io/apimachinery/pkg/api/resource.')):
            return 'snapshot'
        if id=='k8s.io/apimachinery/pkg/util/wait.Backoff':return 'snapshot'
        if id in ('k8s.io/apimachinery/pkg/runtime.Object','k8s.io/apimachinery/pkg/runtime.Unstructured','k8s.io/apimachinery/pkg/runtime.CacheableObject','k8s.io/apimachinery/pkg/api/meta.List','k8s.io/apimachinery/pkg/api/meta.Type'):return 'snapshot'
        if id in ('k8s.io/apimachinery/pkg/runtime.RawExtension','k8s.io/apimachinery/pkg/runtime.Unknown','k8s.io/apimachinery/pkg/runtime.VersionedObjects'):return 'snapshot'
        if id == 'time.Time': return 'snapshot'
        if id.startswith('sigs.k8s.io/structured-merge-diff/v6/schema.'): return 'snapshot'
        if u.get('kind') in ('predeclared','slice','map','array'): return 'snapshot'
        if u.get('kind') in ('interface','function','channel','struct'): return 'identity'
        return 'identity'

    def interface_methods(id,d):
        out={}; pending=[]
        def visit(node,seen):
            if node.get('kind')=='ref':
                ref=node['id']
                if ref in seen:return
                if ref not in types:pending.append(node);return
                visit(types[ref]['shape']['underlying'],seen+[ref])
            elif node.get('kind')=='interface':
                for field in node['members']:
                    if field['names']:
                        for name in field['names']:out.setdefault(name,[]).append({'signature':field['type']})
                    else:visit(field['type'],seen)
            elif node=={'kind':'predeclared','name':'error'}:
                out.setdefault('Error',[]).append({'signature':{'kind':'function','parameters':[],'results':[{'names':[],'type':{'kind':'predeclared','name':'string'}}]}})
            else:pending.append(node)
        visit(d['shape']['underlying'],[id])
        return {'methods':out,'non_method_elements':pending,'conflicting_signatures':[]}

    graph['interface_method_sets']={id:[interface_methods(id,d)] for id,d in types.items() if underlying(d['shape']['underlying']).get('kind')=='interface'}

    def module(p):
        return packages.setdefault(p, header+['package ' + safe(p.rsplit('/',1)[-1]), '', 'import canonical "' + MOD + '/deps/types"', 'import support "' + MOD + '/deps/support"', ''])

    canonical = header+['package types', '', 'import support "' + MOD + '/deps/support"', '', 'type ObjectType[A] = ObjectTypeHandle']
    for id,d in sorted(types.items()):
        shape=d['shape']; tps=[name for f in shape.get('type_parameters',[]) for name in f['names']]
        registry.append('RegisterMode('+json.dumps(id)+','+json.dumps(mode(id,d))+')')
        generics='['+', '.join(tps)+']' if tps else ''
        if shape['kind']=='alias':
            try:
                alias=native(shape['underlying'])
                if shape['underlying'].get('kind')=='ref' and underlying(shape['underlying']).get('kind')=='interface':
                    alias=alias.removeprefix('Option[').removesuffix(']')
                canonical.append('alias ' + names[id] + generics + ' = ' + alias.replace('canonical.',''))
            except ValueError as e: issue(id, 'alias: ' + str(e))
        else: canonical.append('type ' + names[id] + generics + ' = ' + names[id] + 'Handle')
        coverage['types'][id]={'canonical':names[id], 'mode':mode(id,d), 'source':d['source'], 'line':d['line'], 'alias':shape['kind']=='alias','synthetic_anonymous_interface':d.get('synthetic',False)}
        p,n=id.rsplit('.',1); lines=module(p)
        # Private source names are exported with a marked native spelling, not guessed layouts.
        local=local_type(n)
        lines.append('alias ' + local + generics + ' = canonical.' + names[id] + generics)
        if shape['kind']=='alias' and shape['underlying']['kind'] in ('predeclared','slice','function'):
            continue
        if tps:
            symbol='ZeroLike_'+names[id]
            identity=mode(id,d)=='identity'
            hosts.append('func '+symbol+'(v any) any {return '+('ZeroIdentityLike' if identity else 'ZeroLike')+'(v)}')
            lines.append('extern func zero'+local+'Like'+generics+'(prototype '+local+generics+') '+('IO['+local+generics+']' if identity else local+generics)+' = "'+HOST+'".'+symbol)
            coverage['types'][id]['constructor']='explicit existing-instantiation witness; no erased-type guessing'
        elif accessible(id) and len(defs.get(id,[d]))==1:
            try:
                gt=go({'kind':'ref','id':id})
                u=underlying(shape['underlying'])
                if u.get('kind')=='interface' and (shape['underlying'].get('kind') in ('binary_constraint','unary_constraint') or any(m['type'].get('kind') in ('binary_constraint','unary_constraint') for m in u.get('members',[]))): raise ValueError('constraint-only interface')
                registry.append('RegisterType('+json.dumps(id)+', reflect.TypeFor['+gt+']())')
                if u.get('kind')!='interface':
                    symbol='New_'+names[id]
                    identity=mode(id,d)=='identity'
                    hosts.append('func '+symbol+'() any { return '+('NewIdentity' if identity else 'New')+'('+json.dumps(id)+') }')
                    lines.append('extern func new'+local+'() '+('IO['+local+']' if identity else local)+' = "'+HOST+'".'+symbol)
            except ValueError as e: issue(id, str(e))
        else: issue(id, 'private/internal or platform-variant type: no guessed zero constructor')
        local=local+generics
        u=underlying(shape['underlying'])
        if u.get('kind')=='struct':
            field_index=0
            for f in u['fields']:
                fnames=f['names']
                if not fnames:
                    node=f['type']
                    while node.get('kind') in ('pointer','instantiation'): node=node.get('element',node.get('base'))
                    fnames=[node['id'].rsplit('.',1)[1]] if node.get('kind')=='ref' else []
                for name in fnames:
                    index=field_index
                    field_index+=1
                    key=id+'.'+name
                    if not exported(name): coverage['fields'][key]={'status':'private Go state; not exposed','source':d['source'],'line':f['line']};continue
                    try: nt=native(f['type'])
                    except ValueError as e: issue(key,str(e));continue
                    get='Get_'+names[id]+'_'+safe(name); put='With_'+names[id]+'_'+safe(name)
                    if mode(id,d)=='identity':
                        hosts.extend(['func '+get+'(v any) any { return IdentityField(v,'+json.dumps(id)+',[]int{'+str(index)+'}) }','func '+put+'(v,x any) any { return SetIdentityField(v,'+json.dumps(id)+',[]int{'+str(index)+'},x) }'])
                        lines.extend(['extern func '+lower(local)+'Get'+name+'Identity'+generics+'(value '+local+') IO['+nt+'] = "'+HOST+'".'+get,'extern func '+lower(local)+'Set'+name+'Identity'+generics+'(value '+local+', field '+nt+') IO[Unit] = "'+HOST+'".'+put])
                        status='typed effectful identity field access'
                    else:
                        hosts.extend(['func '+get+'(v any) any { return Field(v,'+json.dumps(id)+',[]int{'+str(index)+'}) }','func '+put+'(v,x any) any { return WithField(v,'+json.dumps(id)+',[]int{'+str(index)+'},x) }'])
                        lines.extend(['extern func '+lower(local)+'Get'+name+generics+'(value '+local+') '+nt+' = "'+HOST+'".'+get,'extern func '+lower(local)+'With'+name+generics+'(value '+local+', field '+nt+') '+local+' = "'+HOST+'".'+put])
                        status='typed get and copy-on-write update'
                    coverage['fields'][key]={'status':status,'path':[index],'native_type':nt,'source':d['source'],'line':f['line']}
        elif u.get('kind') in ('predeclared','slice','array','map'):
            try:
                nt=native(u); gt='Underlying_'+names[id]; st='From_'+names[id]
                hosts.append('func '+gt+'(v any) any { return Underlying(v,'+json.dumps(id)+') }')
                if tps:
                    hosts.append('func '+st+'(p,v any) any { return UnderlyingLike(p,v) }')
                    lines.extend(['extern func '+lower(local)+'Value'+generics+'(value '+local+') '+nt+' = "'+HOST+'".'+gt,'extern func '+lower(local)+'WithValue'+generics+'(prototype '+local+', value '+nt+') '+local+' = "'+HOST+'".'+st])
                else:
                    hosts.append('func '+st+'(v any) any { return FromUnderlying('+json.dumps(id)+',v) }')
                    lines.extend(['extern func '+lower(local)+'Value(value '+local+') '+nt+' = "'+HOST+'".'+gt,'extern func '+lower(local)+'FromValue(value '+nt+') '+local+' = "'+HOST+'".'+st])
            except ValueError as e: issue(id,str(e))
        elif u.get('kind')=='function':
            try:
                ps=params_of(u); rt=outcome_type(u); symbol='Invoke_'+names[id];indices=update_indices(u)
                hosts.append('func '+symbol+'('+','.join(['v any']+['a'+str(i)+' any' for i in range(len(ps))])+') any { return Invoke(v,[]int{'+','.join(map(str,indices))+'}'+''.join(',a'+str(i) for i in range(len(ps)))+') }')
                lines.append('extern func '+lower(local)+'Invoke'+generics+'('+', '.join(['value '+local]+['p'+str(i)+' '+native(x) for i,x in enumerate(ps)])+') IO['+rt+'] = "'+HOST+'".'+symbol)
            except ValueError as e: issue(id,str(e))

    # Methods and referenced package functions preserve all result positions, including errors.
    for id,variants in sorted(defs.items()):
        d=variants[0]
        if d['kind']!='func': continue
        if id=='time.Unix':
            module('time').append('extern func unix(seconds Int, nanos Int) Time = "'+HOST+'".TimeUnix')
